def _tracked() -> list:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"],  # noqa: F821
                         capture_output=True, check=True)
    return sorted(f for f in out.stdout.decode().split("\0") if f)


def _head(rel: str, n: int = 4) -> str:
    """The first n lines, or "" for anything unreadable as text."""
    try:
        return "\n".join((ROOT / rel).read_text().splitlines()[:n])  # noqa: F821
    except (UnicodeDecodeError, OSError):
        return ""


