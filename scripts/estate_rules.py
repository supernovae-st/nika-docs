# Poster frames: a bitmap under images/ is a poster only if its video twin is
# tracked. Computed, because the pairing lives in the tree, not in a glob.
_VIDEO_STEMS = {pathlib.Path(f).stem for f in _tracked()
                if f.startswith("videos/") and f.endswith((".mp4", ".webm"))}
for _f in _tracked():
    _stem = pathlib.Path(_f).stem
    if _f.startswith("images/") and _f.endswith(".png") and _stem in _VIDEO_STEMS:
        FILES.append({
            "path": _f, "class": "authored",
            "evidence": f"poster frame paired with videos/{_stem}.mp4/.webm (wired as the <video poster=…>) · extraction pipeline is not in this repo",
            "note": "unverified-default",
        })


